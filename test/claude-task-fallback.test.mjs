import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { randomUUID } from "node:crypto";
import { claudeLaunchPreflight, prepareClaudeDraft, findClaudeDraftSession, prepareClaudeTaskLink } from "../src/claude-task-fallback.js";

function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "relay-claude-draft-"));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  return root;
}
test("the Task-in-the-box link names the Task, folder and project, carries the person's words as far as the link allows, never the agent document", (t) => {
  const root = fixture(t), cwd = path.join(root, "work");
  fs.mkdirSync(cwd);
  let persisted;
  const packet = { forHuman: "Please set the homepage.", forAgent: "agent-only-context", source: { workspace: { label: "relay-companion" } } };
  const link = prepareClaudeTaskLink({ id: "relay_1", cwd, title: "Set the\nhomepage", packet, preflight: { remoteControlDefault: true }, persist: (s) => { persisted = s; } });
  assert.equal(persisted, link);
  assert.equal(link.taskLink, true);
  assert.equal(link.preflight.remoteControlDefault, true);
  const url = new URL(link.url);
  assert.equal(url.searchParams.get("folder"), cwd);
  const q = url.searchParams.get("q");
  assert.equal(q, link.taskPrompt);
  assert.match(q, /Relay Task relay_1 \(“Set the homepage”\)/);
  assert.match(q, /relay_inbox_list with relayIds \["relay_1"\]/);
  assert.ok(q.includes(`carry it out in ${cwd}, their checkout of the relay-companion project`));
  assert.match(q, /relay_task_start[\s\S]*relay_task_complete/);
  assert.match(q, /For the person:\nPlease set the homepage\.$/);
  assert.doesNotMatch(q, /agent-only-context/);
  assert.equal(fs.readdirSync(cwd).length, 0, "no transcript: Claude creates the conversation itself");
  const long = prepareClaudeTaskLink({ id: "relay_1", cwd, title: "T", packet: { forHuman: "word ".repeat(2000) }, persist: () => {} });
  assert.ok(long.url.length <= 2000, `link stays within protocol-handler limits (${long.url.length})`);
  assert.match(long.taskPrompt, /For the person:\nword word[\s\S]*…$/);
  assert.match(long.taskPrompt, /relay_task_complete/, "the instructions are never the part that is cut");
  const bare = prepareClaudeTaskLink({ id: "relay_1", cwd, title: "", packet: {}, persist: () => {} });
  assert.doesNotMatch(bare.taskPrompt, /For the person/);
  assert.throws(() => prepareClaudeTaskLink({ id: "", cwd, title: "T", packet: {}, persist: () => {} }), /Nothing to run/);
});
test("preflight counts live desktop processes, not working tasks or the RC default", async (t) => {
  const root = fixture(t);
  const put = (name, value) => fs.writeFileSync(path.join(root, name), JSON.stringify(value));
  put("1.json", { pid: 1, entrypoint: "claude-desktop", status: "idle" });
  put("duplicate.json", { pid: 1, entrypoint: "claude-desktop" });
  put("dead.json", { pid: 2, entrypoint: "claude-desktop" });
  put("cli.json", { pid: 3, entrypoint: "cli" });
  put("claude_desktop_config.json", { preferences: { ccRemoteControlDefaultEnabled: true } });
  const args = { registry: root, configDirs: [root], version: "2.7032.0", totalMemory: 16 * 1024 ** 3, isAlive: (pid) => pid !== 2 };
  const free = await claudeLaunchPreflight(args);
  assert.equal(free.liveProcesses, 1);
  assert.equal(free.manual, false);
  assert.equal(free.remoteControlDefault, true);
  for (let i = 4; i < 9; i++) put(`${i}.json`, { pid: i, entrypoint: "claude-desktop" });
  assert.equal((await claudeLaunchPreflight(args)).reason, "capacity");
  assert.equal((await claudeLaunchPreflight({ ...args, totalMemory: 64 * 1024 ** 3 })).manual, false);
  assert.equal((await claudeLaunchPreflight({ ...args, version: "future" })).reason, "unknown_version");
});
test("draft carries workspace and a bounded handshake, creates no transcript, binds only exact user input", (t) => {
  const root = fixture(t), cwd = path.join(root, "space & unicode é");
  fs.mkdirSync(cwd);
  let persisted;
  const draft = prepareClaudeDraft({ cwd, title: "Test\n" + "x".repeat(20000), persist: (s) => { persisted = s; } });
  assert.equal(persisted, draft);
  const url = new URL(draft.url);
  assert.equal(url.searchParams.get("folder"), cwd);
  assert.equal(url.searchParams.get("q"), draft.draftPrompt);
  assert.ok(draft.url.length < 2000);
  assert.equal(fs.readdirSync(cwd).length, 0);
  assert.equal(findClaudeDraftSession(draft, { home: root }), null);
  const dir = path.join(root, "projects", cwd.replace(/[^a-zA-Z0-9]/g, "-"));
  fs.mkdirSync(dir, { recursive: true });
  const id = randomUUID(), file = path.join(dir, `${id}.jsonl`);
  const row = { type: "user", sessionId: id, cwd, message: { content: draft.draftPrompt } };
  for (const patch of [{ type: "assistant" }, { isSidechain: true }, { sessionId: "wrong" }, { message: { content: [{ type: "tool_result", content: draft.draftPrompt }] } }]) {
    fs.writeFileSync(file, JSON.stringify({ ...row, ...patch }) + "\n");
    assert.equal(findClaudeDraftSession(draft, { home: root }), null);
  }
  fs.writeFileSync(file, JSON.stringify(row) + "\n");
  assert.equal(findClaudeDraftSession(draft, { home: root }).nativeId, id);
  const other = randomUUID();
  fs.writeFileSync(path.join(dir, `${other}.jsonl`), JSON.stringify({ ...row, sessionId: other }) + "\n");
  assert.throws(() => findClaudeDraftSession(draft, { home: root }), /more than one/);
});
test("a draft Claude opened without the chosen folder is still found, and says where it opened", (t) => {
  const root = fixture(t), cwd = path.join(root, "relay"), elsewhere = path.join(root, "home");
  fs.mkdirSync(cwd);
  const draft = prepareClaudeDraft({ cwd, title: "T", persist: () => {} });
  const dir = path.join(root, "projects", elsewhere.replace(/[^a-zA-Z0-9]/g, "-"));
  fs.mkdirSync(dir, { recursive: true });
  const id = randomUUID();
  fs.writeFileSync(path.join(dir, `${id}.jsonl`), JSON.stringify({ type: "user", sessionId: id, cwd: elsewhere, message: { content: draft.draftPrompt } }) + "\n");
  const bound = findClaudeDraftSession(draft, { home: root });
  assert.equal(bound.nativeId, id);
  assert.equal(bound.cwd, cwd, "the chosen folder is kept for the Task");
  assert.equal(bound.openedCwd, elsewhere);
  const old = new Date(Date.parse(draft.draftCreatedAt) - 60000);
  fs.utimesSync(dir, old, old);
  assert.equal(findClaudeDraftSession(draft, { home: root }), null, "folders untouched since the draft are not read");
});
